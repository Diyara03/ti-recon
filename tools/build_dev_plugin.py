"""Assemble a NON-DISTRIBUTABLE developer copy of the TI Recon plugin.

What it is for
--------------

Proving Claude Code's plugin mechanics against the *real* local MCP server —
that the plugin validates and loads, that the Skill is discovered under the
plugin namespace, that the server starts automatically, that the configured
credentials reach it and the omitted ones leave a source ``not_configured`` —
before any runtime is packaged. The committed plugin under ``plugins/ti-recon``
bundles no runtime and its launcher fails closed; this script produces a copy
whose launcher runs **this checkout's own virtual environment**.

Why that copy must never be distributed
---------------------------------------

The generated launcher carries an absolute path into this developer's checkout.
Installed anywhere else it would point at a directory that does not exist, and
installed on this machine it would run whatever is in the working tree. Every
generated artifact says so: the plugin description, a ``NON_DISTRIBUTABLE`` file
at the plugin root and the launcher's own header. A test asserts the *committed*
plugin contains none of those markers and no absolute path, so the two cannot
be confused by a script that copies the wrong directory.

Usage
-----

.. code-block:: bash

    uv run python tools/build_dev_plugin.py            # -> build/dev-plugin/ti-recon
    claude plugin validate build/dev-plugin/ti-recon
    claude --plugin-dir build/dev-plugin/ti-recon

``build/`` is git-ignored. The output keeps the plugin name ``ti-recon`` so the
Skill namespace and the MCP tool names are exactly those of the real plugin.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "ti-recon"
DEFAULT_OUTPUT = ROOT / "build" / "dev-plugin" / "ti-recon"

#: The console script the checkout's environment provides.
DEV_SERVER = ROOT / ".venv" / "bin" / "ti-recon-mcp"

#: The phrase every generated artifact carries, and the committed plugin never.
MARKER = "NON-DISTRIBUTABLE developer proof"

_LAUNCHER = """\
#!/bin/sh
# {marker}: runs the ti-recon-mcp installed in ONE developer checkout.
# Generated by tools/build_dev_plugin.py. Do not commit, package or distribute.
exec "{server}" "$@"
"""

_NOTICE = """\
{marker}

This directory was generated by tools/build_dev_plugin.py from the committed
plugin at plugins/ti-recon. Its launcher execs an absolute path into one
developer's checkout:

    {server}

It exists only to prove Claude Code's plugin mechanics against the real local
MCP server. It is not the analyst-installable plugin, must not be published to a
marketplace, and must not be copied to another machine.
"""


def build(output: Path = DEFAULT_OUTPUT, *, server: Path = DEV_SERVER) -> Path:
    """Write the developer copy to ``output`` and return its path."""
    if not server.is_file():
        msg = f"development server not found: {server} (run `uv sync --all-extras`)"
        raise FileNotFoundError(msg)
    if output.exists():
        shutil.rmtree(output)
    shutil.copytree(PLUGIN, output, ignore=shutil.ignore_patterns("__pycache__"))

    manifest_path = output / ".claude-plugin" / "plugin.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["description"] = f"{MARKER} — {manifest['description']}"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    launcher = output / "bin" / "ti-recon-mcp"
    launcher.write_text(_LAUNCHER.format(marker=MARKER, server=server), encoding="utf-8")
    launcher.chmod(0o755)

    (output / "NON_DISTRIBUTABLE").write_text(
        _NOTICE.format(marker=MARKER, server=server), encoding="utf-8"
    )
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT, help=f"default: {DEFAULT_OUTPUT}"
    )
    args = parser.parse_args(argv)
    path = build(args.output)
    print(f"{MARKER} written to {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
