def is_decisive_basis(claim: NormalizedClaim) -> bool:
    """Whether one claim can carry a malicious verdict on its own.

    Exact scope, decisive role, malicious direction. The conjunction is the
    point: a decisive semantic at host scope is not a basis, and neither is a
    decisive semantic pointing benign, which has its own rule.
    """
    return (
        claim.is_malicious_direction
        and claim.scope in _EXACT_SCOPES
        and decision_role_for(claim) is ClaimDecisionRole.DECISIVE
    )


def is_benign_basis(claim: NormalizedClaim) -> bool:
    """Whether one claim is a genuine directional benign assertion.

    Only a provider actually asserting benignness qualifies. Warninglist context,
    business-service membership, popularity, an offline state, a code signature
    and an absence of detections are none of them assertions, and none reaches
    this function -- they are not claims at all.
    """
    return (
        claim.effect is EvidenceEffect.SUPPORTS_BENIGN
        and claim.scope in _EXACT_SCOPES
        and claim.semantic is ClaimSemantic.BENIGN_REPUTATION
    )
