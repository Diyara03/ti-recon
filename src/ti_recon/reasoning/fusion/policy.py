"""The deterministic verdict and confidence policy (Task 17C/D).

Rules, in a fixed precedence, over structured facts. No score, no weight, no
probability, no arithmetic of any kind -- and that is a considered position
rather than an omission. There is no calibration data behind any coefficient
anybody could write here, so a weighted formula would manufacture precision that
looks defensible, cannot be explained to an analyst, and shifts unpredictably
when a provider is added. A rule hierarchy can always answer "which rule decided
this, and why", which is the question that actually gets asked.

What decides a verdict
----------------------

Specificity, not popularity. One curated repository holding this exact file as a
known malware sample is worth more than five providers agreeing it "looks
malicious", because the first is a statement about the artifact and the second is
five opinions -- possibly five copies of one opinion. So a single decisive claim
can reach MALICIOUS, and a single generic reputation claim cannot.

The four verdicts answer different questions, and the pair most often confused is
SUSPICIOUS and INCONCLUSIVE. SUSPICIOUS means *there is an affirmative reason for
concern*. INCONCLUSIVE means *the engine cannot justify either direction*. Missing
data, a provider that returned nothing, a sandbox that ran nothing -- none of
those is a reason for concern, and reporting them as suspicion would flood an
analyst with alarm generated by absence.

What can never reach LIKELY_BENIGN
----------------------------------

A warninglist hit, business-service context, shared hosting, a scanner
classification, an offline URL, an absence of detections, a provider returning
NO_DATA, a sandbox that observed no execution, a low detection count, a valid
code signature. Each of those has been refused deliberately at an earlier layer,
and each is refused again here, because the failure mode is a clean-looking
verdict on something that was never examined.
"""

