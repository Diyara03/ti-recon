REPUTATION = ProviderCapability.REPUTATION
INTELLIGENCE = ProviderCapability.MALWARE_INTELLIGENCE
BEHAVIOUR = ProviderCapability.FILE_BEHAVIOR

#: The EICAR test file's SHA-256 — a real entry in the shipped warninglist
#: snapshot, so the context signal comes from the dataset rather than a stub.
EICAR = "275a021bbfb6489e54d471899f7db9d1663fc695ec2fe2a2c4538aabf651fd0f"

USER = "analyst"


async def _investigate(providers: list[ScriptedProvider]):
    """Run one investigation with the scripted providers plus the local dataset."""
    adapters = [*providers, MispWarningListsAdapter()]
    registry = ProviderRegistry(adapters)
    profiles = ProviderPlanningRegistry(
        tuple(build_default_planning_registry().all())
        + tuple(profile_for(item.spec) for item in providers)
    )
    clock = ManualClock()
    secrets, connections = InMemorySecretStore(), InMemoryConnectionRepository()
    manager = CredentialManager(secrets, connections)
    for provider in providers:
        await manager.create_connection(
            user_id=USER,
            provider_id=provider.descriptor.provider_id,
            secret="fake-key",
            auth_type=AuthType.API_KEY,
            status=CredentialStatus.ACTIVE,
        )
    executor = ProviderExecutor(
        credential_resolver=CredentialResolver(secrets, connections),
        cache=InMemoryProviderCache(clock=clock),
        quota_store=InMemoryQuotaStore(clock=clock),
        cooldown_store=InMemoryCooldownStore(clock=clock),
        limiter=ConcurrencyLimiter(max_concurrency=2),
        policies=ProviderPolicyRegistry(policies=[]),
        clock=clock,
        sleeper=RecordingSleeper(clock),
        jitter=FixedJitter(0.0),
    )
    base = build_default_reasoning_engines()
    engines = type(base)(
        temporal=base.temporal,
        false_positive=base.false_positive,
        # The shipped translators plus one per fake, so a scripted claim reaches
        # a real semantic instead of arriving unclassified.
        fusion=EvidenceFusionEngine(translators=_semantics_for(providers)),
        readiness=base.readiness,
    )
    orchestrator = InvestigationOrchestrator(
        correlation=CorrelatedInvestigationOrchestrator(
            enrichment=AdaptiveEnrichmentOrchestrator(
                planner=AdaptiveEnrichmentPlanner(registry=registry, profiles=profiles),
                executor=executor,
                registry=registry,
            )
        ),
        engines=engines,
        clock=clock,
    )
    return await orchestrator.investigate(
        InvestigationRequest(root=normalize_file_hash(EICAR)),
        ExecutionContext(authenticated_user_id=USER),
    )


@pytest.mark.asyncio
async def test_an_explanation_covers_the_evidence_it_was_linked_to() -> None:
    """A real alternative explanation, from the real warninglist snapshot.

    The EICAR digest is a test artifact, so a repository identifying it as
    known malware is a detection the artifact's nature accounts for. Task 16
    says so; the report shows the explanation against that evidence and nothing
    else.
    """
    repository = ScriptedProvider(
        spec("repo", family="fam_repo", capabilities=frozenset({INTELLIGENCE, REPUTATION})),
        {EICAR: claim_evidence(ClaimSemantic.MALWARE_SAMPLE_IDENTITY)},
    )

    result = await _investigate([repository])
    report = build_analyst_report(result)

    assert report.alternative_explanations.items
    explanation = report.alternative_explanations.items[0]
    assert explanation.reason_code == "expected_test_artifact_detection"
    # Linked to specific evidence, and the ids travel with it.
    assert explanation.explains_evidence_ids
    # Task 17 acted on it; the report copied the outcome rather than deciding it.
    assert report.assessment.verdict is Verdict.LIKELY_BENIGN

    rendered = render_text(report)
    assert "expected_test_artifact_detection" in rendered
    assert "applies to 1 evidence item" in rendered
    # Never generalised into a claim about the investigation.
    assert "false positive" not in rendered.lower()


@pytest.mark.asyncio
async def test_an_explanation_is_not_generalised_to_every_finding() -> None:
    """Two detections, one explained. The other must stay visible.

    "It is a test artifact" accounts for a repository recognising the digest and
    accounts for nothing a sandbox watched the file *do* — so the observed
    behaviour is linked as opposing rather than folded in, and remains
    unexplained. Summarising this as "all detections explained" is the failure
    this test exists to prevent.
    """
    repository = ScriptedProvider(
        spec("repo", family="fam_repo", capabilities=frozenset({INTELLIGENCE, REPUTATION})),
        {EICAR: claim_evidence(ClaimSemantic.MALWARE_SAMPLE_IDENTITY)},
    )
    sandbox = ScriptedProvider(
        spec("sandbox", family="fam_sandbox", capabilities=frozenset({BEHAVIOUR})),
        {
            EICAR: claim_evidence(
                ClaimSemantic.SANDBOX_CLASSIFICATION,
                evidence_class=EvidenceClass.DIRECT_OBSERVATION,
            )
        },
    )

    result = await _investigate([repository, sandbox])
    report = build_analyst_report(result)

    explained = {
        evidence_id
        for item in report.alternative_explanations.items
        for evidence_id in item.explains_evidence_ids
    }
    unexplained = {item.evidence_id for item in report.unexplained_evidence.items}

    assert explained, "the test-artifact explanation should still apply"
    assert unexplained, "the observed behaviour must not be folded into it"
    assert not (explained & unexplained)

    rendered = render_text(report)
    assert "not accounted for by any explanation" in rendered


@pytest.mark.asyncio
async def test_the_local_runtime_investigates_with_no_credential_at_all() -> None:
    """The shipped composition, end to end, offline.

    A fresh install has no keys. It must still produce an honest report rather
    than failing — and must disclose nothing while doing it, which is why the
    only registered adapter is the one that answers from a packaged snapshot.
    """
    from ti_recon.application import AnalystInvestigationRequest, InvestigationApplication
    from ti_recon.cli.runtime import build_local_context, build_local_runtime

    application = InvestigationApplication(orchestrator=build_local_runtime())

    report = await application.investigate(
        AnalystInvestigationRequest(observable="example.com"), build_local_context()
    )

    assert report.schema_version
    assert report.source_checks.items
    # Nothing was concluded, and the gaps say exactly which capabilities nobody
    # could serve rather than implying the observable is uninteresting.
    assert report.assessment.verdict is Verdict.INCONCLUSIVE
    assert report.gaps.items
    assert render_text(report)


@pytest.mark.asyncio
async def test_a_disagreement_is_shown_as_a_disagreement() -> None:
    """Two sources, same proposition, opposite directions.

    Nothing balances them, picks a winner or averages them away: Task 17 keeps
    real surviving support at SUSPICIOUS, records the conflict and caps the
    confidence band. The report shows all three, because an analyst deciding
    what to do with contradictory intelligence needs to know it contradicts.
    """
    from fixtures.investigation import InvestigationStack, file_root
    from ti_recon.enums import EvidenceEffect

    accusing = ScriptedProvider(
        spec("accusing", family="fam_a", capabilities=frozenset({REPUTATION})),
        {EICAR: claim_evidence(ClaimSemantic.MALICIOUS_REPUTATION)},
    )
    clearing = ScriptedProvider(
        spec("clearing", family="fam_b", capabilities=frozenset({REPUTATION})),
        {
            EICAR: claim_evidence(
                ClaimSemantic.MALICIOUS_REPUTATION, effect=EvidenceEffect.SUPPORTS_BENIGN
            )
        },
    )
    stack = InvestigationStack(providers=[accusing, clearing])
    await stack.add_credentials()
    result = await stack.orchestrator.investigate(
        InvestigationRequest(root=file_root(EICAR)), stack.context()
    )

    report = build_analyst_report(result)

    assert report.assessment.verdict is Verdict.SUSPICIOUS
    assert len(report.conflicts.items) == 1
    conflict = report.conflicts.items[0]
    assert conflict.malicious_claim_ids and conflict.benign_claim_ids
    # The disagreement is why the band is held down, and the report says so.
    assert report.assessment.confidence_caps

    rendered = render_text(report)
    assert "Unresolved disagreement" in rendered
    assert "malicious: 1 / benign: 1" in rendered
    assert "Confidence limited by:" in rendered
