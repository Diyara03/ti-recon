"""Whole investigations, through every real layer (Task 20).

The other report tests script a provider and assert the projection. These run
the *shipped* local dataset provider alongside a scripted one, so the context
that produces an alternative explanation is generated by real Task 15 policy
against the real snapshot rather than by a fixture asserting the answer.

That matters most for the case an analyst is most likely to be misled by: a
detection that a legitimate explanation accounts for, standing beside one it
does not.
"""

